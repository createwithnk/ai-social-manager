export function preferredLocale(saved: unknown, browserLanguages: readonly string[] = []): Locale {
  if (saved === 'en' || saved === 'ar') return saved
  for (const language of browserLanguages) {
    const base = language.toLowerCase().split('-')[0]
    if (base === 'en' || base === 'ar') return base
  }
  return 'en'
}

export function translate(locale: Locale, message: string, values: Record<string, string | number> = {}) {
  const text = locale === 'ar' && Object.hasOwn(arabicMessages, message) ? arabicMessages[message] : message
  return text.replace(/\{(\w+)\}/g, (token, key: string) => Object.hasOwn(values, key) ? String(values[key]) : token)
}

export function localizedError(locale: Locale, message: string) {
  if (locale === 'en' || Object.hasOwn(arabicMessages, message)) return translate(locale, message)
  const limit = message.match(/^Caption and hashtags exceed the (\d+) character limit\.$/)
  if (limit) return translate(locale, 'Caption and hashtags exceed the {limit} character limit.', { limit: limit[1] })
  return translate(locale, 'This action could not be completed.')
}

export const formatNumber = (locale: Locale, value: number) => new Intl.NumberFormat(localeTags[locale]).format(value)
export const formatPrice = (locale: Locale, amount: number) => new Intl.NumberFormat(localeTags[locale], { style: 'currency', currency: 'INR', currencyDisplay: 'code' }).format(amount / 100)
export function formatDate(locale: Locale, value: string, includeTime = true) {
  const date = new Date(value)
  if (!Number.isFinite(date.getTime())) return translate(locale, 'unavailable')
  return new Intl.DateTimeFormat(localeTags[locale], { calendar: 'gregory', dateStyle: 'medium', ...(includeTime ? { timeStyle: 'short' as const } : {}) }).format(date)
}
