import { matchesMediaHeader, mediaFormats } from '../../../supabase/functions/_shared/media-validation.ts'
import { checkAbort, DriveImportError, IMPORT_LIMITS, type DriveSnapshot, type PickedDriveFile, type VerifiedDriveFile } from './types.ts'

const fields = 'id,name,mimeType,size,version,modifiedTime,sha256Checksum,trashed,isAppAuthorized,capabilities(canDownload)'
const safeId = /^[A-Za-z0-9_-]{5,180}$/
export const pickerMimeTypes = Object.keys(mediaFormats).join(',')
export function pickedFiles(value: unknown): PickedDriveFile[] {
  if (!Array.isArray(value) || !value.length || value.length > IMPORT_LIMITS.files) throw new DriveImportError('selection')
  const seen = new Set<string>()
  return value.map(item => {
    if (!item || typeof item !== 'object' || typeof item.id !== 'string' || !safeId.test(item.id) || seen.has(item.id) || (item.resourceKey && (typeof item.resourceKey !== 'string' || !/^[A-Za-z0-9_-]{1,200}$/.test(item.resourceKey)))) throw new DriveImportError('selection')
    seen.add(item.id)
    return { id: item.id, ...(item.resourceKey ? { resourceKey: item.resourceKey as string } : {}) }
  })
}
function object(value: unknown): Record<string, unknown> { if (!value || typeof value !== 'object' || Array.isArray(value)) throw new DriveImportError('download'); return value as Record<string, unknown> }
function snapshot(value: unknown, selected: PickedDriveFile): DriveSnapshot {
  const item = object(value), capability = object(item.capabilities)
  if (item.id !== selected.id || item.trashed !== false || item.isAppAuthorized !== true || capability.canDownload !== true) throw new DriveImportError('download')
  if (typeof item.mimeType !== 'string' || !Object.hasOwn(mediaFormats, item.mimeType)) throw new DriveImportError('unsupported')
  if (typeof item.size !== 'string' || !/^\d{1,16}$/.test(item.size) || !Number.isSafeInteger(Number(item.size)) || Number(item.size) < 1 || Number(item.size) > IMPORT_LIMITS.fileBytes) throw new DriveImportError('size')
  if (typeof item.version !== 'string' || !/^\d{1,30}$/.test(item.version) || typeof item.modifiedTime !== 'string' || item.modifiedTime.length > 40 || !Number.isFinite(Date.parse(item.modifiedTime))) throw new DriveImportError('download')
  if (typeof item.name !== 'string' || !item.name.trim() || item.name.length > 512) throw new DriveImportError('download')
  if (item.sha256Checksum !== undefined && (typeof item.sha256Checksum !== 'string' || !/^[a-f0-9]{64}$/i.test(item.sha256Checksum))) throw new DriveImportError('download')
  // A sanitized display/original name; opaque private storage names are generated by Velo.
  const name = [...item.name].map(char => char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127 || char === '/' || char === '\\' ? '_' : char).join('').slice(0, 200)
  return { ...selected, name, mimeType: item.mimeType, bytes: Number(item.size), version: item.version, modifiedTime: item.modifiedTime, ...(typeof item.sha256Checksum === 'string' ? { sha256: item.sha256Checksum.toLowerCase() } : {}) }
}
export function assertBatch(items: readonly DriveSnapshot[]) {
  pickedFiles(items)
  if (items.some(item => !Number.isSafeInteger(item.bytes) || item.bytes < 1 || item.bytes > IMPORT_LIMITS.fileBytes) || items.reduce((total, item) => total + item.bytes, 0) > IMPORT_LIMITS.batchBytes) throw new DriveImportError('size')
}
function sameRevision(a: DriveSnapshot, b: DriveSnapshot) { return a.id === b.id && a.version === b.version && a.modifiedTime === b.modifiedTime && a.bytes === b.bytes && a.mimeType === b.mimeType && a.sha256 === b.sha256 }
export async function contentSha256(bytes: Uint8Array<ArrayBuffer>): Promise<string> { return [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(byte => byte.toString(16).padStart(2, '0')).join('') }

export function createDriveContent(getToken: () => string, fetcher: typeof fetch = fetch, deadlineMs = 20000) {
  // IDs, not user URLs. Redirects, webContentLink, shortcuts, downloads of Docs,
  // permission mutation and arbitrary targets are deliberately unsupported.
  async function read(selected: PickedDriveFile, media: boolean, signal: AbortSignal): Promise<{ bytes: Uint8Array<ArrayBuffer>; type: string }> {
    pickedFiles([selected]); checkAbort(signal)
    const token = getToken()
    if (!/^[\x21-\x7e]{1,4096}$/.test(token)) throw new DriveImportError('expired')
    const url = new URL(`https://www.googleapis.com/drive/v3/files/${selected.id}`)
    if (media) url.searchParams.set('alt', 'media'); else url.searchParams.set('fields', fields)
    url.searchParams.set('supportsAllDrives', 'true')
    const abort = new AbortController(); let reader: ReadableStreamDefaultReader<Uint8Array> | undefined
    const cancel = () => { abort.abort(); void reader?.cancel().catch(() => {}) }
    let timer: ReturnType<typeof setTimeout> | undefined
    const maximum = media ? IMPORT_LIMITS.fileBytes : 32768
    let disposeSignal: () => void = () => {}
    const stopped = new Promise<never>((_, reject) => {
      const stop = () => { cancel(); reject(new DriveImportError('cancelled')) }
      signal.addEventListener('abort', stop, { once: true }); disposeSignal = () => signal.removeEventListener('abort', stop)
      timer = setTimeout(() => { cancel(); reject(new DriveImportError('download')) }, deadlineMs)
    })
    try {
      return await Promise.race([stopped, (async () => {
        const headers: Record<string, string> = { Authorization: `Bearer ${token}` }
        if (selected.resourceKey) headers['X-Goog-Drive-Resource-Keys'] = `${selected.id}/${selected.resourceKey}`
        const response = await fetcher(url.toString(), { method: 'GET', headers, mode: 'cors', credentials: 'omit', redirect: 'error', cache: 'no-store', referrerPolicy: 'no-referrer', signal: abort.signal })
        reader = response.body?.getReader()
        if (response.status === 401) throw new DriveImportError('expired')
        if (!response.ok || response.redirected || (response.url && response.url !== url.toString()) || Number(response.headers.get('Content-Length')) > maximum) throw new DriveImportError('download')
        const type = (response.headers.get('Content-Type') ?? '').split(';')[0].trim().toLowerCase()
        if (!media && type !== 'application/json') throw new DriveImportError('download')
        if (!reader) throw new DriveImportError('download')
        const chunks: Uint8Array[] = []; let length = 0
        while (true) { const part = await reader.read(); if (part.done) break; length += part.value.byteLength; if (length > maximum) throw new DriveImportError('size'); chunks.push(part.value) }
        checkAbort(signal)
        const bytes = new Uint8Array(length); let offset = 0
        for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.length }
        return { bytes, type }
      })()])
    } catch (error) { if (signal.aborted) throw new DriveImportError('cancelled'); if (error instanceof DriveImportError) throw error; throw new DriveImportError('download') }
    finally { clearTimeout(timer); disposeSignal(); cancel() }
  }
  async function inspectOne(selected: PickedDriveFile, signal: AbortSignal): Promise<DriveSnapshot> {
    const result = await read(selected, false, signal)
    try { return snapshot(JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(result.bytes)), selected) }
    catch (error) { if (error instanceof DriveImportError) throw error; throw new DriveImportError('download') }
  }
  return {
    async inspect(files: readonly PickedDriveFile[], signal: AbortSignal): Promise<DriveSnapshot[]> {
      const items: DriveSnapshot[] = []
      for (const file of pickedFiles(files)) { items.push(await inspectOne(file, signal)); if (items.reduce((total, item) => total + item.bytes, 0) > IMPORT_LIMITS.batchBytes) throw new DriveImportError('size') }
      assertBatch(items); return items
    },
    async download(selected: DriveSnapshot, signal: AbortSignal): Promise<VerifiedDriveFile> {
      const before = await inspectOne(selected, signal)
      if (!sameRevision(before, selected)) throw new DriveImportError('changed')
      const { bytes, type } = await read(selected, true, signal)
      if (bytes.length !== before.bytes || (type !== before.mimeType && type !== 'application/octet-stream') || !matchesMediaHeader(before.mimeType, bytes.subarray(0, 16))) throw new DriveImportError('unsupported')
      const sha256 = await contentSha256(bytes)
      if (before.sha256 && sha256 !== before.sha256) throw new DriveImportError('changed')
      const after = await inspectOne(selected, signal)
      if (!sameRevision(before, after)) throw new DriveImportError('changed')
      checkAbort(signal)
      return { file: new File([bytes], before.name, { type: before.mimeType }), snapshot: before, sha256 }
    },
  }
}
