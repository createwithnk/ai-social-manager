import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile, readdir } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'

test('review-only Beta migration enforces invites, budgets, trusted outcomes and bounded errors', async () => {
  const db = new PGlite()
  const A='a1111111-1111-4111-8111-111111111111', B='b2222222-2222-4222-8222-222222222222'
  const SA='a3333333-3333-4333-8333-333333333333', SB='b4444444-4444-4444-8444-444444444444'
  const scalar = async (sql, args=[]) => Object.values((await db.query(sql,args)).rows[0])[0]
  const as = async (role, uid, sid) => {
    await db.exec('reset role')
    await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ role, sub: uid, session_id: sid, user_metadata: { admin: true, beta: true } })])
    await db.exec(`set role ${role}`)
  }
  try {
    await db.exec(await readFile('tests/local-bootstrap.sql','utf8'))
    for (const file of (await readdir('supabase/migrations')).filter(n => n.endsWith('.sql')).sort()) await db.exec(await readFile(`supabase/migrations/${file}`,'utf8'))
    await db.query('insert into auth.users(id) values($1),($2)',[A,B])
    await db.query('insert into auth.sessions(id,user_id) values($1,$2),($3,$4)',[SA,A,SB,B])
    await as('authenticated',A,SA)
    await db.query("insert into public.posts(user_id,idea,platform,tone,caption,status) values($1,'Existing draft','Instagram','Friendly','Keep me','draft')",[A])
    await db.query("insert into storage.objects(bucket_id,name) values('post-media',$1)",[`${A}/existing.png`])
    await as('postgres')
    await db.exec(await readFile('supabase/proposals/20261015000000_private_beta_safety.sql','utf8'))
    await as('authenticated',A,SA)
    assert.equal(await scalar('select public.beta_access()'),false)
    assert.equal(await scalar('select count(*)::int from public.posts'),0)
    assert.equal(await scalar('select count(*)::int from storage.objects'),0)
    assert.equal(await scalar("select public.reserve_ai_request('gemini-2.5-flash')"),null)
    assert.equal(await scalar('select public.consume_ai_quota()'),false)
    await assert.rejects(db.query('select * from private.beta_controls'))
    await assert.rejects(db.query('insert into private.beta_members(user_id,expires_at) values($1,now()+interval \'1 day\')',[A]))
    await assert.rejects(db.query("insert into public.posts(user_id,idea,platform,tone,caption,status) values($1,'Uninvited','Instagram','Friendly','No','draft')",[A]))
    await as('postgres')
    await db.query("insert into private.beta_members(user_id,expires_at) values($1,now()+interval '1 day')",[A])
    await db.query('insert into private.owner_admins(user_id) values($1)',[A])
    await as('authenticated',A,SA)
    assert.equal(await scalar('select public.beta_access()'),true)
    assert.equal(await scalar('select count(*)::int from public.posts'),1)
    assert.equal(await scalar('select count(*)::int from storage.objects'),1)
    assert.equal(await scalar("select public.reserve_ai_request('gemini-2.5-flash')"),null)
    await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('post-media',$1)",[`${A}/blocked.png`]))
    await as('postgres')
    // Synthetic rates/config in memory only. Never use them as real prices.
    await db.exec('update private.beta_controls set ai_enabled=true,daily_call_limit=2,daily_budget_usd=0.04,request_reserve_usd=0.02,input_usd_per_million=1,output_usd_per_million=2,max_output_tokens=1024')
    await as('authenticated',A,SA)
    assert.equal(await scalar("select public.reserve_ai_request('gemini-wrong')"),null)
    const first = await scalar("select public.reserve_ai_request('gemini-2.5-flash')")
    assert.equal(first.maxOutputTokens,1024)
    assert.equal(await scalar('select public.consume_ai_quota()'),false)
    assert.equal(await scalar('select calls from public.ai_usage'),1)
    await assert.rejects(db.query('select public.finish_ai_request($1,\'success\',10,20,50)',[first.id]))
    await as('service_role')
    await assert.rejects(db.query('select * from private.ai_requests'))
    assert.equal(await scalar('select public.finish_ai_request($1,\'success\',100,200,50)',[first.id]),true)
    assert.equal(await scalar('select public.finish_ai_request($1,\'success\',100,200,50)',[first.id]),false)
    await as('authenticated',A,SA)
    const second = await scalar("select public.reserve_ai_request('gemini-2.5-flash')")
    assert.ok(second.id)
    assert.equal(await scalar("select public.reserve_ai_request('gemini-2.5-flash')"),null)
    const summary = await scalar('select public.owner_monitoring()')
    assert.equal(summary.operations.attempts,2)
    assert.equal(summary.operations.committedUsd,0.04)
    assert.equal(summary.operations.estimatedUsd,0.0005)
    assert.equal(summary.operations.pending,1)
    assert.equal(summary.operations.inputTokens,100)
    await as('service_role')
    assert.equal(await scalar('select public.finish_ai_request($1,\'timeout\',null,null,25000)',[second.id]),true)
    await as('authenticated',A,SA)
    assert.equal((await scalar('select public.owner_monitoring()')).operations.missingUsage,1)
    assert.equal((await scalar('select public.owner_monitoring()')).operations.errors,1)
    assert.equal((await scalar('select public.owner_monitoring()')).operations.committedUsd,0.04)
    await as('postgres')
    await db.query("update private.ai_requests set day=(now() at time zone 'UTC')::date-1 where id=$1",[second.id])
    await as('authenticated',A,SA)
    assert.equal((await scalar('select public.owner_monitoring()')).operations.carryoverUsd,0.02)
    assert.equal((await scalar('select public.owner_monitoring()')).operations.committedUsd,0.04)
    assert.equal(await scalar("select public.reserve_ai_request('gemini-2.5-flash')"),null)
    assert.equal(await scalar("select public.report_runtime_error('raw-secret-message')"),false)
    for(let i=0;i<20;i++) assert.equal(await scalar("select public.report_runtime_error('render_failed')"),true)
    assert.equal(await scalar("select public.report_runtime_error('save_failed')"),false)
    await as('authenticated',B,SB)
    assert.equal(await scalar('select public.beta_access()'),false)
    assert.equal(await scalar("select public.report_runtime_error('render_failed')"),false)
    await assert.rejects(db.query('select public.owner_monitoring()'))
    await as('postgres')
    await db.exec('update private.beta_controls set daily_call_limit=100,daily_budget_usd=10')
    await as('authenticated',A,SA)
    // Calls serialize on the configuration row and stop at the existing per-user cap.
    const requests = await Promise.all(Array.from({length:21},()=>scalar("select public.reserve_ai_request('gemini-2.5-flash')")))
    assert.equal(requests.filter(Boolean).length,18)
    assert.equal(await scalar('select calls from public.ai_usage'),20)
    await as('service_role')
    assert.equal(await scalar('select public.finish_ai_request($1,\'success\',-1,1,1)',[requests[0].id]),false)
    assert.equal(await scalar('select public.finish_ai_request($1,\'success\',null,1,1)',[requests[0].id]),false)
    assert.equal(await scalar('select public.finish_ai_request($1,\'success\',1000000,1,1)',[requests[0].id]),true)
    await as('postgres')
    assert.equal(await scalar('select ai_enabled from private.beta_controls'),false)
    await db.query("update private.beta_members set expires_at=now()-interval '1 second' where user_id=$1",[A])
    await as('authenticated',A,SA)
    assert.equal(await scalar('select public.beta_access()'),false)
    await as('postgres')
    await db.query("update private.beta_members set expires_at=now()+interval '1 day',revoked=true where user_id=$1",[A])
    await as('authenticated',A,SA)
    assert.equal(await scalar('select public.beta_access()'),false)
    await as('postgres')
    await db.query('update private.beta_members set revoked=false where user_id=$1',[A])
    await db.query('delete from auth.sessions where id=$1',[SA])
    await as('authenticated',A,SA)
    assert.equal(await scalar('select public.beta_access()'),false)
    assert.equal(await scalar('select count(*)::int from public.posts'),0)
    await as('anon')
    await assert.rejects(db.query('select public.beta_access()'))
    await assert.rejects(db.query("select public.reserve_ai_request('gemini-2.5-flash')"))
    await as('postgres')
    assert.equal(await scalar('select publishing_enabled or billing_enabled from private.launch_controls'),false)
    assert.equal(await scalar('select count(*)::int from public.posts'),1)
    const ledgerBefore = await scalar('select count(*)::int from private.ai_requests')
    await db.exec(await readFile('supabase/proposals/20261015000000_private_beta_safety.rollback.sql','utf8'))
    assert.equal(await scalar('select ai_enabled or uploads_enabled from private.beta_controls'),false)
    assert.equal(await scalar('select count(*)::int from private.ai_requests'),ledgerBefore)
    assert.equal(await scalar('select count(*)::int from public.posts'),1)
    assert.equal(await scalar('select count(*)::int from storage.objects'),1)
    await as('authenticated',B,SB)
    assert.equal(await scalar('select public.beta_access()'),false)
    await assert.rejects(db.query("select public.reserve_ai_request('gemini-2.5-flash')"))
    assert.equal(await scalar('select public.consume_ai_quota()'),false)
    await assert.rejects(db.query("select public.report_runtime_error('render_failed')"))
    await as('service_role')
    await assert.rejects(db.query('select public.finish_ai_request($1,\'success\',1,1,1)',[first.id]))
  } finally { await db.close() }
})
