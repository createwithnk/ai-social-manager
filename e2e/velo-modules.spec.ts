import { expect, test, type Page } from '@playwright/test'

const sample = { id: 'velo-synthetic-post', idea: 'An approved UAE offer', caption: 'A reviewed caption', hashtags: ['UAE'], platform: 'Instagram', tone: 'Friendly', status: 'approved', revision: 2, createdAt: '2026-10-01T00:00:00Z' }
async function tools(page: Page, name = 'Velo tools', menu = 'Open navigation') {
  if (await page.getByRole('button', { name: menu, exact: true }).isVisible()) await page.getByRole('button', { name: menu, exact: true }).click()
  await page.getByRole('button', { name, exact: true }).click()
}
test.beforeEach(async ({ page }) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/')
  await page.evaluate(post => localStorage.setItem('aasiflow-posts', JSON.stringify([post])), sample)
  await page.reload()
})
test('Velo bookmark and bulk CSV workflows preserve existing saved posts through refresh', async ({ page }) => {
  await expect(page).toHaveTitle('Velo — Content workspace')
  await expect(page.locator('.brand strong')).toHaveText('Velo')
  await tools(page)
  await expect(page.getByRole('heading', { name: 'Velo tools', exact: true })).toBeFocused()
  await page.getByLabel('Asset name', { exact: true }).fill('My test design')
  await page.getByLabel('Canva or Drive link', { exact: true }).fill('https://www.canva.com/design/ABCDE/shareSegment/edit?utm_source=test')
  await page.getByRole('button', { name: 'Save link', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Link saved')
  await expect(page.getByRole('link', { name: 'Open asset: My test design', exact: true })).toHaveAttribute('href', 'https://www.canva.com/design/ABCDE/view')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download template CSV', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('velo-canva-bulk.csv')
  expect(await download.failure()).toBeNull()
  await page.reload(); await tools(page)
  await expect(page.getByRole('link', { name: 'Open asset: My test design', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remove bookmark: My test design', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Open asset: My test design', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('aasiflow-posts') ?? '[]'))).toEqual([sample])
})
test('asset links reject secret-bearing URLs and preserve corrupt local bookmark data', async ({ page }) => {
  await tools(page)
  await page.getByLabel('Asset name', { exact: true }).fill('Unsafe test link')
  await page.getByLabel('Canva or Drive link', { exact: true }).fill('https://www.canva.com/design/ABCDE/view?access_token=synthetic')
  await page.getByRole('button', { name: 'Save link', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('without access tokens')
  await expect(page.locator('.velo-assets li')).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('velo:asset-links:v1:local-preview', 'corrupt-fixture'))
  await page.reload(); await tools(page)
  await expect(page.getByRole('alert')).toContainText('No links were overwritten')
  await page.getByLabel('Asset name', { exact: true }).fill('Fresh link')
  await page.getByLabel('Canva or Drive link', { exact: true }).fill('https://www.canva.com/design/ABCDE/view')
  await page.getByRole('button', { name: 'Save link', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('velo:asset-links:v1:local-preview'))).toBe('corrupt-fixture')
})
test('all publisher previews remain closed and leave approval and schedule data unchanged', async ({ page }) => {
  await tools(page)
  await page.getByRole('button', { name: 'Publisher preview', exact: true }).click()
  await page.getByLabel('Saved post', { exact: true }).selectOption(sample.id)
  for (const id of ['instagram', 'tiktok', 'youtube-shorts', 'snapchat', 'google-business']) {
    await page.getByLabel('Platform', { exact: true }).selectOption(id)
    await page.getByRole('button', { name: 'Check publishing plan', exact: true }).click()
    await expect(page.getByText('Live publishing is disabled.', { exact: true })).toBeVisible()
  }
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('aasiflow-posts') ?? '[]'))).toEqual([sample])
  await expect(page.getByRole('button', { name: /^Publish$|^Connect account$|^Send$/ })).toHaveCount(0)
})
test('a blocked bookmark write shows a safe error and leaves the existing workspace usable', async ({ page }) => {
  await tools(page)
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key.startsWith('velo:asset-links:')) throw new DOMException('private-storage-sentinel', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.getByLabel('Asset name', { exact: true }).fill('Quota test')
  await page.getByLabel('Canva or Drive link', { exact: true }).fill('https://www.canva.com/design/ABCDE/view')
  await page.getByRole('button', { name: 'Save link', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No saved bookmarks were changed')
  await expect(page.locator('body')).not.toContainText('private-storage-sentinel')
  await expect(page.locator('.velo-assets li')).toHaveCount(0)
  if (await page.getByRole('button', { name: 'Open navigation', exact: true }).isVisible()) await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('button', { name: 'View', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('aasiflow-posts') ?? '[]'))).toEqual([sample])
})
