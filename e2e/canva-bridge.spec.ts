test('Canva manual reference maps and survives refresh without altering old posts or another owner',async({page})=>{
  await page.goto('/canva-bridge-fixture')
  await page.evaluate(()=>localStorage.setItem('aasiflow-posts','unchanged-fixture'))
  await page.getByLabel('Creative name',{exact:true}).fill('My brand template')
  await page.getByLabel('Canva design or Brand Template URL',{exact:true}).fill('https://www.canva.com/brand/brand-templates/template_fixture')
  await page.getByRole('button',{name:'Save link',exact:true}).click()
  await expect(page.getByText('Link only — account access is unverified.',{exact:true}).first()).toBeVisible()
  await page.getByLabel('Scheduled post',{exact:true}).selectOption('post_fixture')
  await page.getByRole('button',{name:'Map selected creative',exact:true}).click()
  await expect(page.getByText('Matches the current scheduled post',{exact:true})).toBeVisible()
  await page.reload();await expect(page.getByText('Matches the current scheduled post',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Switch test owner',exact:true}).click();await expect(page.getByText('No mappings yet.',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>localStorage.getItem('aasiflow-posts'))).toBe('unchanged-fixture')
  await expect(page.locator('body')).not.toHaveAttribute('data-reads')
})
