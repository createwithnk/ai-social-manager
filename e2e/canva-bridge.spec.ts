test('Canva corrupt records are preserved and temporarily blocked storage can recover without resetting data',async({page})=>{
  await page.goto('/canva-bridge-fixture')
  await page.evaluate(()=>localStorage.setItem('velo:canva-bridge:v1:a1111111-1111-4111-8111-111111111111','corrupt-fixture'))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('Browser records could not be read or saved')
  await expect(page.getByRole('button',{name:'Save link',exact:true})).toBeDisabled()
  expect(await page.evaluate(()=>localStorage.getItem('velo:canva-bridge:v1:a1111111-1111-4111-8111-111111111111'))).toBe('corrupt-fixture')
  await page.goto('/canva-bridge-fixture?mode=recover-storage')
  await expect(page.getByRole('alert')).toContainText('Browser records could not be read or saved')
  await page.getByRole('button',{name:'Unblock synthetic storage',exact:true}).click()
  await page.getByRole('button',{name:'Reload browser records',exact:true}).click()
  await page.getByLabel('Creative name',{exact:true}).fill('Recovered creative')
  await page.getByLabel('Canva design or Brand Template URL',{exact:true}).fill('https://www.canva.com/design/design_fixture/view')
  await page.getByRole('button',{name:'Save link',exact:true}).click()
  await expect(page.getByText('Link saved in this browser.',{exact:true})).toBeVisible()
})
