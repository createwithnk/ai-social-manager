import { expect, test } from '@playwright/test'
test.beforeEach(async ({ page }) => {
 await page.route('**/*', route => {
  const url = new URL(route.request().url())
  if (url.hostname !== '127.0.0.1') return route.abort()
  if (url.pathname === '/whatsapp-lead-agent-fixture') return route.fulfill({ contentType:'text/html', body:`<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module">import RefreshRuntime from '/@react-refresh';RefreshRuntime.injectIntoGlobalHook(window);window.$RefreshReg$=()=>{};window.$RefreshSig$=()=>type=>type;window.__vite_plugin_react_preamble_installed__=true;await import('/e2e/fixtures/whatsapp-lead-agent-harness.tsx');</script></body></html>` })
  return route.continue()
 })
})
test('classifies hot leads and previews owner routing without sending', async ({ page }) => {
 await page.goto('/whatsapp-lead-agent-fixture')
 const panel = page.getByTestId('whatsapp-lead-agent')
 await expect(panel).toBeVisible()
 await panel.getByTestId('wla-owner-number').fill('+14155550123')
 await panel.getByTestId('wla-message').fill('Please book an appointment and tell me the price')
 await panel.getByTestId('wla-classify').click()
 await expect(panel.getByTestId('wla-category')).toHaveText('Hot Lead')
 await expect(panel.getByTestId('wla-routing-preview')).toContainText('+14155550123')
 await expect(panel.getByTestId('wla-preview-message')).toContainText('no message has been sent')
 await expect(panel.getByRole('button', { name:'Send', exact:true })).toHaveCount(0)
})
test('invalid number and FAQ or spam messages never create routing preview', async ({ page }) => {
 await page.goto('/whatsapp-lead-agent-fixture')
 const panel = page.getByTestId('whatsapp-lead-agent')
 await panel.getByTestId('wla-owner-number').fill('12345')
 await panel.getByTestId('wla-message').fill('What are your opening hours?')
 await panel.getByTestId('wla-classify').click()
 await expect(panel.getByTestId('wla-category')).toHaveText('FAQ')
 await expect(panel.getByTestId('wla-routing-preview')).toContainText('preview is available only')
 await panel.getByTestId('wla-message').fill('Free money crypto giveaway, click here')
 await panel.getByTestId('wla-classify').click()
 await expect(panel.getByTestId('wla-category')).toHaveText('Spam')
})
test('Arabic interface uses RTL and fits a mobile viewport', async ({ page }) => {
 await page.goto('/whatsapp-lead-agent-fixture?lang=ar')
 const panel = page.getByTestId('whatsapp-lead-agent')
 await expect(panel).toHaveAttribute('dir','rtl')
 await expect(panel).toHaveAttribute('lang','ar')
 await expect(panel.getByTestId('wla-classify')).toHaveText('تصنيف الرسالة')
 await expect(panel.getByTestId('wla-owner-number')).toBeVisible()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
